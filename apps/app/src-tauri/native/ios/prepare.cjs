#!/usr/bin/env node
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { syncIosIcons } = require("./sync-icons.cjs");

function shellQuote(value) {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

// Called by Xcode, whose environment selects the device/simulator architectures.
function buildShareCore(env = process.env) {
  for (const key of ["PROJECT_DIR", "CONFIGURATION", "EFFECTIVE_PLATFORM_NAME", "PLATFORM_NAME"]) {
    if (!env[key]) throw new Error(`缺少 Xcode 构建环境变量：${key}`);
  }
  let targets;
  if (env.PLATFORM_NAME === "iphoneos") {
    targets = ["aarch64-apple-ios"];
  } else if (env.PLATFORM_NAME === "iphonesimulator") {
    const architectures = env.ARCHS?.trim().split(/\s+/).filter(Boolean) ?? [];
    if (!architectures.length) throw new Error("缺少模拟器架构 ARCHS");
    targets = [...new Set(architectures.map((arch) => {
      if (arch === "arm64") return "aarch64-apple-ios-sim";
      if (arch === "x86_64") return "x86_64-apple-ios";
      throw new Error(`Unsupported simulator architecture: ${arch}`);
    }))];
  } else {
    throw new Error(`Unsupported iOS platform: ${env.PLATFORM_NAME}`);
  }
  const root = path.resolve(__dirname, "../../../../..");
  const manifest = path.join(root, "apps/app/src-tauri/share/core/Cargo.toml");
  const buildDir = path.join(env.PROJECT_DIR, "share-core/target");
  const output = path.join(env.PROJECT_DIR, "share-core", env.CONFIGURATION + env.EFFECTIVE_PLATFORM_NAME);
  const cargoBin = path.join(env.CARGO_HOME || path.join(os.homedir(), ".cargo"), "bin");
  const options = { cwd: root, stdio: "inherit", env: {
    ...env, PATH: cargoBin + path.delimiter + (env.PATH || ""),
  } };
  fs.mkdirSync(output, { recursive: true });
  const archives = targets.map((target) => {
    execFileSync("rustup", ["target", "add", target], options);
    execFileSync("cargo", ["build", "--manifest-path", manifest, "--target", target,
      "--target-dir", buildDir, "--release", "--locked"], options);
    return path.join(buildDir, target, "release/libcliproam_share_upload.a");
  });
  const library = path.join(output, "libcliproam_share_upload.a");
  if (archives.length === 1) fs.copyFileSync(archives[0], library);
  else execFileSync("lipo", ["-create", ...archives, "-output", library], options);
}

// Run after `tauri ios init`, which recreates the untracked Xcode project.
function prepareIos(apple = path.resolve(__dirname, "../../gen/apple"), generate = true) {
  const root = path.resolve(__dirname, "../../../../..");
  const project = fs.readFileSync(path.join(apple, "project.yml"), "utf8");
  const target = project.match(/^  ([\w-]+_iOS):\s*$/m)?.[1];
  if (!target) throw new Error("找不到 Tauri iOS 应用 target");
  const version = require(path.join(root, "package.json")).version;
  const buildVersion = project.match(/^\s+CFBundleVersion:\s*["']?([^\s"']+)/m)?.[1] ?? version;
  const keychainGroup = "$(AppIdentifierPrefix)com.whilecode.cliproam.share-auth";
  const appGroup = { "com.apple.security.application-groups": ["group.com.whilecode.cliproam"],
    "keychain-access-groups": [keychainGroup] };
  const extension = "ClipRoamShare";
  const source = path.join(apple, extension);
  fs.mkdirSync(source, { recursive: true });
  fs.copyFileSync(path.join(root, "apps/app/src-tauri/native/ios/ShareExtension/ShareViewController.swift"),
    path.join(source, "ShareViewController.swift"));
  // Remove sources generated by the previous Swift upload implementation.
  for (const name of ["ShareInbox.swift", "ShareUpload.swift"]) {
    fs.rmSync(path.join(source, name), { force: true });
  }
  const spec = {
    include: ["project.yml"],
    targets: {
      [target]: {
        info: { path: `${target}/Info.plist`, properties: { ShareKeychainAccessGroup: keychainGroup } },
        settings: { base: { ASSETCATALOG_COMPILER_APPICON_NAME: "AppIcon",
          OTHER_LDFLAGS: ["$(inherited)", "-framework", "Security", "-framework", "UniformTypeIdentifiers"] } },
        entitlements: { path: `${target}/${target}.entitlements`, properties: appGroup },
        dependencies: [{ target: extension, embed: true }],
      },
      [extension]: {
        type: "app-extension", platform: "iOS", deploymentTarget: "14.0",
        sources: [{ path: extension, excludes: ["*.plist", "*.entitlements"] }],
        preBuildScripts: [{ name: "Build shared Rust upload core", basedOnDependencyAnalysis: false,
          script: `${shellQuote(process.execPath)} ${shellQuote(__filename)} build-share-core` }],
        settings: { groups: ["app"], base: {
          PRODUCT_NAME: extension, PRODUCT_BUNDLE_IDENTIFIER: "com.whilecode.cliproam.share",
          SWIFT_VERSION: "5.0", APPLICATION_EXTENSION_API_ONLY: true,
          SKIP_INSTALL: true, TARGETED_DEVICE_FAMILY: "1,2",
          GENERATE_INFOPLIST_FILE: false,
          ENABLE_USER_SCRIPT_SANDBOXING: false,
          SWIFT_INCLUDE_PATHS: `"${path.join(root, "apps/app/src-tauri/share/plugin/ios/FFI")}"`,
          LIBRARY_SEARCH_PATHS: ["$(inherited)", "$(PROJECT_DIR)/share-core/$(CONFIGURATION)$(EFFECTIVE_PLATFORM_NAME)"],
          OTHER_LDFLAGS: ["$(inherited)", "-lcliproam_share_upload", "-liconv", "-framework", "Security", "-framework", "UniformTypeIdentifiers"],
        } },
        info: { path: `${extension}/Info.plist`, properties: {
          CFBundleDisplayName: "ClipRoam", CFBundleShortVersionString: version, CFBundleVersion: buildVersion,
          ShareKeychainAccessGroup: keychainGroup,
          NSAppTransportSecurity: { NSAllowsArbitraryLoads: true },
          NSLocalNetworkUsageDescription: "ClipRoam needs access to your local network to upload shared content to your sync server.",
          NSExtension: {
            NSExtensionPointIdentifier: "com.apple.share-services",
            NSExtensionPrincipalClass: "$(PRODUCT_MODULE_NAME).ShareViewController",
            NSExtensionAttributes: { NSExtensionActivationRule: {
              NSExtensionActivationSupportsText: true,
              NSExtensionActivationSupportsWebURLWithMaxCount: 10,
              NSExtensionActivationSupportsImageWithMaxCount: 100,
              NSExtensionActivationSupportsFileWithMaxCount: 100,
              NSExtensionActivationSupportsMovieWithMaxCount: 10,
            } },
          },
        } },
        entitlements: { path: `${extension}/${extension}.entitlements`, properties: appGroup },
      },
    },
  };
  const specPath = path.join(apple, "project.cliproam.json");
  fs.writeFileSync(specPath, JSON.stringify(spec, null, 2) + "\n");
  if (generate) {
    syncIosIcons();
    execFileSync("xcodegen", ["generate", "--spec", specPath], { cwd: apple, stdio: "inherit" });
  }
  console.log("已配置 iOS Share Extension、App Group 和应用图标");
  return spec;
}

module.exports = { prepareIos, buildShareCore };
if (require.main === module) {
  const command = process.argv[2];
  if (command === "build-share-core") buildShareCore();
  else if (!command) prepareIos();
  else throw new Error(`未知命令：${command}`);
}
